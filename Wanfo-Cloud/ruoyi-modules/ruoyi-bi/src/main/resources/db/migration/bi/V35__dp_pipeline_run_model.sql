CREATE TABLE dp_pipeline_run (
    id bigint NOT NULL AUTO_INCREMENT,
    pipeline_id bigint NOT NULL,
    revision_id bigint NOT NULL,
    revision_hash char(64) NOT NULL,
    run_mode varchar(16) NOT NULL DEFAULT 'PREVIEW',
    request_key varchar(96) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    trigger_by varchar(64) NOT NULL,
    trace_id varchar(64) DEFAULT NULL,
    timeout_seconds int NOT NULL DEFAULT 30,
    summary_json json DEFAULT NULL,
    error_summary varchar(500) DEFAULT NULL,
    create_time datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    started_at datetime(3) DEFAULT NULL,
    finished_at datetime(3) DEFAULT NULL,
    duration_ms bigint DEFAULT NULL,
    active_pipeline_id bigint DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_dp_pipeline_run_request (pipeline_id,request_key),
    UNIQUE KEY uk_dp_pipeline_single_active (active_pipeline_id),
    KEY idx_dp_pipeline_run_history (pipeline_id,create_time),
    KEY idx_dp_pipeline_run_status (status,create_time),
    CONSTRAINT fk_dp_pipeline_run_pipeline FOREIGN KEY (pipeline_id) REFERENCES dp_pipeline(id) ON DELETE CASCADE,
    CONSTRAINT fk_dp_pipeline_run_revision FOREIGN KEY (revision_id) REFERENCES dp_pipeline_revision(id)
);

CREATE TABLE dp_pipeline_node_run (
    id bigint NOT NULL AUTO_INCREMENT,
    run_id bigint NOT NULL,
    node_key varchar(96) NOT NULL,
    node_type varchar(40) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'PENDING',
    attempt int NOT NULL DEFAULT 1,
    input_row_count bigint NOT NULL DEFAULT 0,
    output_row_count bigint NOT NULL DEFAULT 0,
    summary_json json DEFAULT NULL,
    error_summary varchar(500) DEFAULT NULL,
    started_at datetime(3) DEFAULT NULL,
    finished_at datetime(3) DEFAULT NULL,
    duration_ms bigint DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_dp_pipeline_node_run (run_id,node_key),
    KEY idx_dp_pipeline_node_run_status (run_id,status),
    CONSTRAINT fk_dp_pipeline_node_run_run FOREIGN KEY (run_id) REFERENCES dp_pipeline_run(id) ON DELETE CASCADE
);
