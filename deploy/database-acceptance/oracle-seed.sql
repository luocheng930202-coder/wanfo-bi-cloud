    district NVARCHAR2(40) NOT NULL,
    channel NVARCHAR2(32) NOT NULL,
    amount NUMBER(18,2) NOT NULL,
    quantity NUMBER(10,0) NOT NULL,
    optional_note NVARCHAR2(80)
);
